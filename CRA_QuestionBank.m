    function put(m, sec, id, question, kind, opts, points, unit, bounds, note, met)
        if nargin < 6 || isempty(opts), opts = {}; end
        if nargin < 7 || isempty(points), points = nan(1,numel(opts)); end
        if nargin < 8, unit = ''; end
        if nargin < 9 || isempty(bounds), bounds = [0 inf]; end
        if nargin < 10, note = ''; end
        if nargin < 11, met = NaN; end
        assert(numel(opts)==numel(points), '选项与分值个数不一致: %s', id);
        item = struct('module',m,'section',sec,'id',id,'text',question,...
            'type',kind,'options',{opts},'scores',points,'unit',unit,...
            'limits',bounds,'hint',note,'met',met);
